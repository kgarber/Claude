function getPuzzleForDate(dateStr) {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = ((hash << 5) - hash + dateStr.charCodeAt(i)) | 0;
  }
  hash = Math.abs(hash);
  const idx = hash % PUZZLE_PAIRS.length;
  const pair = PUZZLE_PAIRS[idx];

  const daysSinceEpoch = Math.floor(new Date(dateStr).getTime() / 86400000);
  const puzzleNum = daysSinceEpoch - 19700; // offset to get reasonable numbers

  const sim = wordSimilarity(pair[0], pair[1]);
  let par;
  if (sim < 0.1) par = 5;
  else if (sim < 0.2) par = 4;
  else if (sim < 0.3) par = 3;
  else par = 3;

  return {
    number: puzzleNum,
    start: pair[0],
    end: pair[1],
    par: par,
    dateStr: dateStr
  };
}
